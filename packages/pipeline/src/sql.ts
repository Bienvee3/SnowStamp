import type { Candidate } from "./candidates.js";
import { OSM_ATTRIBUTION } from "./osm.js";

const sqlText = (value: string): string => `'${value.replace(/'/g, "''")}'`;

function geoJson(candidate: Candidate): string {
  const coordinates = candidate.polygons.map((p) => [p.outer, ...p.holes].map((ring) => ring.map((c) => [c.longitude, c.latitude])));
  return JSON.stringify({ type: "MultiPolygon", coordinates });
}

/**
 * Idempotent seed SQL for the candidates. Geometry is repaired with ST_MakeValid and reduced to polygons,
 * so the table's validity check holds. Existing keys are left untouched (`on conflict do nothing`).
 */
export function seedSql(candidates: readonly Candidate[]): string {
  const header = `-- Generated by @snowstamp/pipeline. ${OSM_ATTRIBUTION}\n-- Review before loading: candidates are not curated.\n`;
  const rows = candidates.map(
    (c) =>
      `insert into public.resorts (key, name, country_code, area) values (${sqlText(c.key)}, ${sqlText(c.name)}, ${sqlText(c.countryCode)}, ` +
      `extensions.ST_Multi(extensions.ST_CollectionExtract(extensions.ST_MakeValid(extensions.ST_SetSRID(extensions.ST_GeomFromGeoJSON(${sqlText(geoJson(c))}), 4326)), 3))) ` +
      `on conflict (key) do nothing; -- ${c.osmRef}`,
  );
  return `${header}${rows.join("\n")}\n`;
}
